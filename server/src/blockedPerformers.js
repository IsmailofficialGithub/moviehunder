/** Unique + sorted for stable diffs. */
export function getBlockedPerformers() {
  const seen = new Set();
  const out = [];
  for (const raw of BLOCKED_PERFORMERS) {
    const n = String(raw || "")
      .toLowerCase()
      .replace(/[^a-z0-9\s]/g, " ")
      .replace(/\s+/g, " ")
      .trim();
    if (!n || seen.has(n)) continue;
    // Skip very short single-token names (too many false positives)
    if (!n.includes(" ") && n.length < 5) continue;
    seen.add(n);
    out.push(n);
  }
  out.sort();
  return out;
}
